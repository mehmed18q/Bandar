"""Generate bandar/web/js/icon-data.js from a Simple Icons package (CC0-1.0).

    npm pack simple-icons && tar -xzf simple-icons-*.tgz -C /tmp/si
    python scripts/make_icons.py /tmp/si/package

Only the listed logos are embedded, so the interface works offline. Brand names
and logos remain trademarks of their owners; they identify the technology only.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# key in Bandar → Simple Icons slug
BRANDS = {
    "postgresql": "postgresql",
    "mysql": "mysql",
    "mariadb": "mariadb",
    "mongodb": "mongodb",
    "redis": "redis",
    "clickhouse": "clickhouse",
    "cassandra": "apachecassandra",
    "scylladb": "scylladb",
    "cockroachdb": "cockroachlabs",
    "timescale": "timescale",
    "influxdb": "influxdb",
    "neo4j": "neo4j",
    "elasticsearch": "elasticsearch",
    "opensearch": "opensearch",
    "meilisearch": "meilisearch",
    "kafka": "apachekafka",
    "rabbitmq": "rabbitmq",
    "nats": "natsdotio",
    "pulsar": "apachepulsar",
    "temporal": "temporal",
    "minio": "minio",
    "docker": "docker",
    "kubernetes": "kubernetes",
    "helm": "helm",
    "nginx": "nginx",
    "traefik": "traefikproxy",
    "etcd": "etcd",
    "consul": "consul",
    "vault": "vault",
    "argo": "argo",
    "grafana": "grafana",
    "prometheus": "prometheus",
    "jaeger": "jaeger",
    "sentry": "sentry",
    "keycloak": "keycloak",
    "jenkins": "jenkins",
    "gitlab": "gitlab",
    "airflow": "apacheairflow",
}


def main():
    package = Path(sys.argv[1])
    data = json.loads((package / "data" / "simple-icons.json").read_text())
    entries = data if isinstance(data, list) else data.get("icons", [])
    colors = {}
    for entry in entries:
        slug = entry.get("slug") or re.sub(r"[^a-z0-9]", "", entry["title"].lower())
        colors[slug] = entry["hex"]
    icons = {}
    for key, slug in BRANDS.items():
        svg = (package / "icons" / f"{slug}.svg").read_text()
        title = re.search(r"<title>(.*?)</title>", svg).group(1)
        path = re.search(r'<path d="([^"]+)"', svg).group(1)
        if not re.fullmatch(r"[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+", path):
            raise ValueError(f"Unexpected path data in {slug}")
        icons[key] = {
            "title": title.replace("&amp;", "&"),
            "hex": colors.get(slug, "6B7280"),
            "path": path,
        }
    version = json.loads((package / "package.json").read_text())["version"]
    output = ROOT / "bandar" / "web" / "js" / "icon-data.js"
    output.write_text(
        f"/* Generated by scripts/make_icons.py from Simple Icons {version} (CC0-1.0).\n"
        " * Logos are trademarks of their owners and only identify the technology. */\n"
        f"window.BandarBrandIcons = {json.dumps(icons, indent=1)};\n",
        encoding="utf-8",
    )
    print(f"{len(icons)} icons → {output}")


if __name__ == "__main__":
    main()
